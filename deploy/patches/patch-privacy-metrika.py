#!/usr/bin/env python3
"""Правит раздел 6 политики конфиденциальности в собранном чанке: сайт больше не
«без аналитических счётчиков», а с Яндекс Метрикой и названным обработчиком.

Использование (на сервере):
    python3 patch-privacy-metrika.py ~/www/indoor-golf.ru/assets/PrivacyPage-BOd6B0Ku-IDG9.js

Идемпотентно, рядом кладёт резервную копию `<имя>.bak-metrika`.
Исходники в репозитории правятся отдельно (src/pages/PrivacyPage.tsx).
"""
import shutil
import sys
from pathlib import Path

OLD = ('Сайт не использует рекламные и аналитические счётчики. В браузере могут сохраняться '
       'только технические настройки интерфейса, например выбранная тема и отметка о показе '
       'заставки. Они не применяются для рекламного профилирования. Сторонняя карта не '
       'загружается до отдельного действия посетителя.')

NEW = ('Сайт использует Яндекс Метрику — сервис статистики посещений, оператор ООО «ЯНДЕКС», '
       'ИНН 7736207543; обработка ведётся на инфраструктуре в Российской Федерации. Счётчик '
       'собирает обезличенные сведения о визите: просмотренные страницы, источник перехода, тип '
       'устройства и браузера, приблизительный регион по IP-адресу, действия на странице. Эти '
       'сведения нужны, чтобы понимать, откуда приходят посетители и насколько удобен сайт; для '
       'рекламного профилирования на сторонних площадках они не применяются. Отказаться от сбора '
       'можно, запретив файлы cookie в настройках браузера. Кроме счётчика в браузере сохраняются '
       'технические настройки интерфейса, например выбранная тема и отметка о показе заставки. '
       'Сторонняя карта не загружается до отдельного действия посетителя.')


def main(target):
    p = Path(target)
    s = p.read_text(encoding='utf-8')
    if NEW in s:
        print(f'{p.name}: текст уже обновлён')
        return 0
    if OLD not in s:
        print(f'{p.name}: исходная формулировка не найдена — проверить вручную', file=sys.stderr)
        return 1
    backup = p.with_name(p.name + '.bak-metrika')
    if not backup.exists():
        shutil.copy2(p, backup)
        print(f'бэкап: {backup.name}')
    p.write_text(s.replace(OLD, NEW, 1), encoding='utf-8')
    print(f'{p.name}: раздел 6 политики обновлён под Яндекс Метрику')
    return 0


if __name__ == '__main__':
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(2)
    sys.exit(main(sys.argv[1]))
